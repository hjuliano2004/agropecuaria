function lerRacaoSalva(nome) {
    const salva = localStorage.getItem(nome);

    if (salva === null) {
        return null;
    }

    let racoes;

    try {
        racoes = JSON.parse(salva);
    } catch (erro) {
        if (erro instanceof SyntaxError) {
            return null;
        }
        throw erro;
    }

    return Array.isArray(racoes) ? racoes : null;
}

function assinaturaRacao(racao) {
    if (!racao || typeof racao !== "object" || Array.isArray(racao)) {
        return null;
    }

    const dados = Object.keys(racao)
        .filter(chave => chave !== "quantidade")
        .sort()
        .map(chave => [chave, racao[chave]]);

    return JSON.stringify(dados);
}

function listasIguais(racoesSalvas, racoesSistema) {
    if (!Array.isArray(racoesSalvas) || !Array.isArray(racoesSistema)
        || racoesSalvas.length !== racoesSistema.length) {
        return false;
    }

    const contagem = new Map();

    for (const racao of racoesSalvas) {
        const assinatura = assinaturaRacao(racao);
        if (assinatura === null) {
            return false;
        }
        contagem.set(assinatura, (contagem.get(assinatura) || 0) + 1);
    }

    for (const racao of racoesSistema) {
        const assinatura = assinaturaRacao(racao);
        const quantidade = contagem.get(assinatura) || 0;
        if (assinatura === null || quantidade === 0) {
            return false;
        }
        contagem.set(assinatura, quantidade - 1);
    }

    return true;
}

function mesmaRacao(a, b) {
    return a.marca === b.marca && a.tipo === b.tipo && a.peso === b.peso;
}

export function verificarRacoes(nome, sistema) {
    return listasIguais(lerRacaoSalva(nome), sistema);
}

export function loadRacao(nome, padrao) {
    const racoesSalvas = lerRacaoSalva(nome);

    if (listasIguais(racoesSalvas, padrao)) {
        return racoesSalvas;
    }

    return padrao.map(racao => {
        const anterior = racoesSalvas?.find(item =>
            item && typeof item === "object" && mesmaRacao(item, racao)
        );
        return {
            ...racao,
            quantidade: Number.isFinite(anterior?.quantidade)
                ? anterior.quantidade
                : racao.quantidade
        };
    });
}









